/**
 * Per-user URL naming.
 *
 * Every public file lives at  /{tag}/{code}.{ext}  where:
 *   - `tag`  is `user.userCode` — user-editable, previous values kept alive in
 *            `user_code_aliases` so links already in circulation never break.
 *   - `code` is generated per upload according to `user.namingScheme`.
 *
 * Changing a scheme only affects NEW uploads: `code` is stored on the row, so
 * the 8k+ links already shared keep resolving byte-for-byte as before.
 */

import { randomInt } from "node:crypto";
import { humanCode } from "@/lib/ids";
import { ADJECTIVES, NOUNS, UNAMBIGUOUS_ALPHABET } from "@/lib/naming-words";

// ---------------------------------------------------------------------------
// Slugification
// ---------------------------------------------------------------------------

/**
 * Latin characters that don't decompose under NFD and would otherwise be
 * dropped entirely (turning "łotego.gif" into "otego").
 */
const TRANSLITERATE: Record<string, string> = {
  ł: "l",
  Ł: "l",
  đ: "d",
  Đ: "d",
  ø: "o",
  Ø: "o",
  æ: "ae",
  Æ: "ae",
  œ: "oe",
  Œ: "oe",
  ß: "ss",
  þ: "th",
  Þ: "th",
  ð: "d",
  Ð: "d",
};

/**
 * Filename → URL-safe slug, preserving meaning across diacritics.
 * "Źródła wiedzy.docx" → "zrodla-wiedzy"
 * "Major Suchodolski - PRZERÓBKA.mp4" → "major-suchodolski-przerobka"
 */
export function slugifyName(input: string): string {
  const mapped = Array.from(input)
    .map((ch) => TRANSLITERATE[ch] ?? ch)
    .join("");
  return mapped
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // strip combining accents
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

/** Strip the extension from a filename before slugifying. */
export function baseName(filename: string): string {
  const i = filename.lastIndexOf(".");
  return i > 0 ? filename.slice(0, i) : filename;
}

// ---------------------------------------------------------------------------
// Tags (the first URL segment)
// ---------------------------------------------------------------------------

/**
 * Names that may never be claimed as the FIRST path segment.
 *
 * Two things depend on this list:
 *   1. a tag must not shadow a top-level route, or the user makes their own
 *      dashboard unreachable;
 *   2. with `user.skipTagInUrl` an upload code itself becomes a first segment
 *      (/name.png), so the same list gates root-level media resolution.
 *
 * Next.js already prefers static routes over the dynamic `[userCode]` segment,
 * so this is defence in depth rather than the only guard — but it also covers
 * routes that do not exist *yet*: reserving them now means a future /help or
 * /pricing cannot be pre-empted by a file someone uploaded today.
 *
 * Matching is case-insensitive. Only exact segments count: a tag `apis` or a
 * file `login-screen.png` is fine.
 */
const RESERVED_TAGS = new Set([
  // routes that exist today
  "api", "_next", "dashboard", "login", "logout", "register", "reset", "forgot",
  "2fa", "verify", "activate", "recover", "upload", "uploads", "oembed", "s",
  "a", "u", "admin", "settings", "profile", "static", "public", "assets",
  "welcome", "trash", "tokens", "paste", "pastes", "links", "folders", "folder",
  // decoration served per account: /bg/{tag} and /avatar/{tag}. `bg` was missing
  // and has been since wallpapers shipped - a tag matching a top-level route
  // loses to it in Next's resolution order, so the account's public pages simply
  // stop existing.
  "bg", "avatar", "avatars",
  // well-known files served from /public or generated by Next
  "favicon.ico", "robots.txt", "sitemap.xml", "well-known", ".well-known",
  "manifest.json", "sw.js", "icon.png", "apple-icon.png", "opengraph-image",
  // kept free for routes we are likely to add
  "auth", "signin", "signup", "signout", "account", "me", "home", "files",
  "file", "share", "embed", "raw", "download", "config", "sharex", "docs",
  "help", "about", "terms", "privacy", "pricing", "contact", "status",
  "health", "healthz", "search", "new", "edit", "delete", "static-assets",
]);

/**
 * Is this segment reserved by the application? Used both when validating a tag
 * and when resolving a tagless (root-level) media link.
 */
export function isReservedTag(segment: string): boolean {
  return RESERVED_TAGS.has(segment.toLowerCase());
}

export interface TagCheck {
  ok: boolean;
  /** Present when ok === false. Message key for i18n + fallback text. */
  reason?: "too-short" | "too-long" | "charset" | "reserved";
}

/**
 * Validate a user-chosen tag. Deliberately permissive on length (production
 * carries legacy tags of 3–12 chars such as `root`, `alicja`, `bobby`) but
 * strict on charset so it stays a clean, unambiguous path segment.
 */
export function checkTag(tag: string): TagCheck {
  if (tag.length < 2) return { ok: false, reason: "too-short" };
  if (tag.length > 32) return { ok: false, reason: "too-long" };
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]*$/.test(tag)) return { ok: false, reason: "charset" };
  if (isReservedTag(tag)) return { ok: false, reason: "reserved" };
  return { ok: true };
}

/**
 * Path of a public file. `tag` is null for owners who opted out of the tag
 * segment (`user.skipTagInUrl`), which puts the code in the root namespace.
 * Returns a path, not an absolute URL, so callers pick their own base.
 */
export function mediaPath(tag: string | null, code: string, ext: string): string {
  const leaf = ext ? `${code}.${ext}` : code;
  return tag ? `/${tag}/${leaf}` : `/${leaf}`;
}

// ---------------------------------------------------------------------------
// Short links
