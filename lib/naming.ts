/** short_links.code is varchar(64) — the scoped form has to fit inside it. */
export const SHORT_CODE_MAX = 64;

/**
 * Short links are namespaced by storing the owner's tag INSIDE the code:
 * `alicja/test` serves /s/alicja/test. The column already carries a global
 * unique index, so this gives per-user namespaces (two people can both own
 * `test`) without touching the table. `tag = null` keeps the legacy root form.
 */
export function scopedShortCode(tag: string | null, code: string): string {
  return tag ? `${tag}/${code}` : code;
}

/** Split a stored short code back into its scope and leaf. */
export function splitShortCode(stored: string): { tag: string | null; code: string } {
  const i = stored.indexOf("/");
  return i === -1
    ? { tag: null, code: stored }
    : { tag: stored.slice(0, i), code: stored.slice(i + 1) };
}

// ---------------------------------------------------------------------------
// Naming schemes (the second URL segment)
// ---------------------------------------------------------------------------

export const NAMING_SCHEMES = [
  "random",
  "words",
  "random-chars",
  "filename",
  "filename-random",
  "date-filename",
  "custom",
] as const;

export type NamingScheme = (typeof NAMING_SCHEMES)[number];

export function isNamingScheme(v: string | null | undefined): v is NamingScheme {
  return !!v && (NAMING_SCHEMES as readonly string[]).includes(v);
}

// ── Scheme parameters ──────────────────────────────────────────────────────
//
// Both are stored per user (user.naming_word_count / user.naming_random_length)
// and clamped here rather than at the edge, so a hand-crafted request cannot
// ask for a 1-character code (trivially enumerable) or a 400-word one.

export const WORD_COUNT_MIN = 2;
export const WORD_COUNT_MAX = 4;
export const WORD_COUNT_DEFAULT = 2;

/**
 * Five characters over a 56-symbol alphabet is ~550 million codes — plenty for
 * a personal instance, and short enough to read aloud. Below that the namespace
 * becomes small enough to walk, so it is a hard floor.
 */
export const RANDOM_LENGTH_MIN = 5;
export const RANDOM_LENGTH_MAX = 32;
export const RANDOM_LENGTH_DEFAULT = 6;

function clamp(value: number | null | undefined, min: number, max: number, fallback: number): number {
  // `null` has to be caught BEFORE the numeric coercion: `Number(null)` is 0,
  // which is perfectly finite, so a NULL column (rows that predate the
  // parameter, or an explicit reset) would clamp to the minimum instead of
  // falling back to the documented default.
  if (value == null) return fallback;
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.min(max, Math.max(min, Math.round(n)));
}

export function clampWordCount(v: number | null | undefined): number {
  return clamp(v, WORD_COUNT_MIN, WORD_COUNT_MAX, WORD_COUNT_DEFAULT);
}

export function clampRandomLength(v: number | null | undefined): number {
  return clamp(v, RANDOM_LENGTH_MIN, RANDOM_LENGTH_MAX, RANDOM_LENGTH_DEFAULT);
}

// ── Generators ─────────────────────────────────────────────────────────────

function sample<T>(list: readonly T[]): T {
  return list[randomInt(0, list.length)];
}

/**
 * Gyazo-style readable code: `funny-cat`, `ineffable-guitar`,
 * `misty-golden-otter`. The LAST word is always the noun; everything before it
 * is an adjective, which is what makes three- and four-word codes still read as
 * a phrase instead of a word salad.
 *
 * Adjectives are drawn without replacement so `warm-warm-ember` cannot happen.
 */
export function wordCode(count: number = WORD_COUNT_DEFAULT): string {
  const n = clampWordCount(count);
  const adjectives: string[] = [];
  // n-1 distinct adjectives. The pool is 236 long, so the retry loop is bounded
  // in practice; the counter is belt-and-braces against a shrunken word list.
  for (let guard = 0; adjectives.length < n - 1 && guard < 100; guard++) {
    const word = sample(ADJECTIVES);
    if (!adjectives.includes(word)) adjectives.push(word);
  }
  return [...adjectives, sample(NOUNS)].join("-");
}

/**
 * Random code over `UNAMBIGUOUS_ALPHABET` — no 0/O/o and no 1/l/I.
 *
 * The omissions are the point: these codes get read off a screen, dictated over
 * a call and retyped by hand, and those two groups are the pairs people
 * actually get wrong. `randomInt` (CSPRNG, rejection-sampled) rather than
 * `Math.random`, because a public URL that can be predicted is a public URL
 * that can be walked.
 */
export function randomCharCode(length: number = RANDOM_LENGTH_DEFAULT): string {
  const n = clamp(length, 1, 128, RANDOM_LENGTH_DEFAULT);
  let out = "";
  for (let i = 0; i < n; i++) out += UNAMBIGUOUS_ALPHABET[randomInt(0, UNAMBIGUOUS_ALPHABET.length)];
  return out;
}

/** Short random suffix used to de-collide readable codes. */
function shortRandom(n = 4): string {
  return humanCode(n).toLowerCase();
}

function two(n: number): string {
  return String(n).padStart(2, "0");
}

/**
 * Sanitizer for custom patterns. Unlike `slugifyName` it preserves case and the
 * underscore, so `{words2}_{rand5}` really yields `funky-otter_fJ4as` instead of
 * being flattened to `funky-otter-fj4as` — the pattern is the user's design and
 * mangling it would make the preview a lie. Everything outside `[A-Za-z0-9._-]`
 * still collapses to a dash, so the result is always a safe path segment.
 */
function sanitizeCode(input: string): string {
  const mapped = Array.from(input)
    .map((ch) => TRANSLITERATE[ch] ?? ch)
    .join("");
  return mapped
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // strip combining accents
    .replace(/[^A-Za-z0-9._-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "")
    .slice(0, 100);
}

/**
 * Expand a custom pattern. Unknown tokens are left alone (then sanitized away),
 * so a malformed pattern degrades to something usable instead of throwing.
 *
 * Tokens:
 *   {name} {ext} {date} {time} {year} {month} {day}
 *   {random} {random:N}   — pronounceable suffix, e.g. kOREMAfi42
 *   {words} {wordsN}      — Gyazo-style words, N = 2..4
 *   {rand} {randN}        — unambiguous random characters, N = 1..32
 */
export function expandPattern(pattern: string, filename: string, now: Date): string {
  const name = slugifyName(baseName(filename));
  const ext = (filename.match(/\.([a-z0-9]+)$/i)?.[1] ?? "").toLowerCase();
  return pattern.replace(/\{(\w+)(?::(\d+))?\}/g, (whole, token: string, arg?: string) => {
    // {words3} / {rand5}: the count rides on the token itself, which is what
    // makes a pattern readable at a glance.
    const sized = /^(words|rand)(\d+)$/.exec(token);
    if (sized) {
      const n = Number(sized[2]);
      return sized[1] === "words" ? wordCode(n) : randomCharCode(n);
    }

    switch (token) {
      case "name":
        return name;
      case "ext":
        return ext;
      case "date":
        return `${now.getFullYear()}-${two(now.getMonth() + 1)}-${two(now.getDate())}`;
      case "time":
        return `${two(now.getHours())}${two(now.getMinutes())}${two(now.getSeconds())}`;
      case "year":
        return String(now.getFullYear());
      case "month":
        return two(now.getMonth() + 1);
      case "day":
        return two(now.getDate());
      case "words":
        return wordCode(arg ? Number(arg) : WORD_COUNT_DEFAULT);
      case "rand":
        return randomCharCode(arg ? Number(arg) : RANDOM_LENGTH_DEFAULT);
      case "random":
        return shortRandom(arg ? Math.min(16, Math.max(1, Number(arg))) : 6);
      default:
        return whole;
    }
  });
}

export interface CodeBaseInput {
  scheme: NamingScheme;
  pattern?: string | null;
  filename: string;
  now?: Date;
  /** Words per code for the `words` scheme (2–4). */
  wordCount?: number | null;
  /** Characters per code for the `random-chars` scheme (5–32). */
  randomLength?: number | null;
}

/**
 * Build the *preferred* code for an upload. The result is a candidate only —
 * `allocateCode` resolves collisions against the unique index on uploads.code.
 */
export function buildCodeBase({
  scheme,
  pattern,
  filename,
  now = new Date(),
  wordCount,
  randomLength,
}: CodeBaseInput): string {
  switch (scheme) {
    case "words":
      return wordCode(clampWordCount(wordCount));
    case "random-chars":
      return randomCharCode(clampRandomLength(randomLength));
    case "filename": {
      return slugifyName(baseName(filename)) || humanCode(10);
    }
    case "filename-random": {
      const slug = slugifyName(baseName(filename));
      return slug ? `${slug}-${shortRandom(4)}` : humanCode(10);
    }
    case "date-filename": {
      const slug = slugifyName(baseName(filename));
      const d = `${now.getFullYear()}-${two(now.getMonth() + 1)}-${two(now.getDate())}`;
      return slug ? `${d}-${slug}` : `${d}-${shortRandom(4)}`;
    }
    case "custom": {
      const expanded = pattern ? sanitizeCode(expandPattern(pattern, filename, now)) : "";
      return expanded || humanCode(10);
    }
    case "random":
    default:
      return humanCode(10);
  }
}

/**
 * A code candidate plus, for the randomised schemes, how to produce a fresh one.
 *
 * `regenerate` exists because the two collision responses are not interchangeable.
 * Appending `-2` to a *name* is right — it reads as "the second file called
 * that". Appending it to a *random* code is wrong twice over: it leaks that a
 * collision happened, and it does nothing about the actual cause, which is that
 * the namespace is filling up. Rolling a longer code does.
 */
export interface CodePlan {
  base: string;
  /**
   * Fresh candidate for collision attempt `n` (1-based), or null to fall back to
   * the numeric ladder.
   */
  regenerate?: (attempt: number) => string;
}

/** How many re-rolls at one width before the generator widens the namespace. */
const WORD_REROLLS_PER_WIDTH = 4;

/**
 * Build the code candidate together with its collision strategy. This is what
 * the upload pipeline calls; `buildCodeBase` remains the pure "first guess".
 */
export function planCode(input: CodeBaseInput): CodePlan {
  const base = buildCodeBase(input);

  if (input.scheme === "random-chars") {
    const length = clampRandomLength(input.randomLength);
    // One extra character per collision. With a 56-symbol alphabet a genuine
    // clash means the pool at this width is saturated, and widening multiplies
    // the space by 56 — retrying at the same width would just clash again.
    return { base, regenerate: (n) => randomCharCode(length + n) };
  }

  if (input.scheme === "words") {
    const count = clampWordCount(input.wordCount);
    return {
      base,
      // Re-roll a few times first (70k+ two-word pairs, so a clash is usually
      // bad luck), then add a word, which multiplies the pool by ~236.
      regenerate: (n) => wordCode(count + Math.floor((n - 1) / WORD_REROLLS_PER_WIDTH)),
    };
  }

  return { base };
}

/**
 * True when the scheme produces guessable URLs. Used to warn the user in the
 * profile UI — with `filename`, anyone who knows the tag and a filename can
 * construct the link without ever being given it.
 *
 * `words` and `random-chars` are not on the list: they are drawn from a CSPRNG
 * and owe nothing to the file's name. (A two-word code is *enumerable* given
 * enough requests, which is a different property — the UI shows the pool size
 * for that.)
 */
export function isGuessable(scheme: NamingScheme): boolean {
  return scheme === "filename" || scheme === "date-filename" || scheme === "custom";
}

/**
 * Resolve a base into a code that is free, given a predicate that reports
 * whether a candidate is already taken.
 *
 * Two strategies, picked by the caller:
 *   - with `regenerate` (random schemes): keep drawing fresh codes, each wider
 *     than the last, so a collision grows the namespace instead of advertising
 *     itself in the URL;
 *   - without it (name-derived schemes): exact base, then -2..-20, then a
 *     random suffix.
 */
export async function allocateCode(
  base: string,
  isTaken: (candidate: string) => Promise<boolean>,
  regenerate?: (attempt: number) => string,
): Promise<string> {
  const clean = base.slice(0, 100) || humanCode(10);

  if (!(await isTaken(clean))) return clean;

  if (regenerate) {
    for (let i = 1; i <= 24; i++) {
      const candidate = regenerate(i).slice(0, 100);
      if (candidate && !(await isTaken(candidate))) return candidate;
    }
    throw new Error(`Could not allocate a unique code for "${clean}"`);
  }

  for (let i = 2; i <= 20; i++) {
    const candidate = `${clean}-${i}`;
    if (!(await isTaken(candidate))) return candidate;
  }

  for (let i = 0; i < 20; i++) {
    const candidate = `${clean}-${shortRandom(5)}`;
    if (!(await isTaken(candidate))) return candidate;
  }

  throw new Error(`Could not allocate a unique code for "${clean}"`);
}
